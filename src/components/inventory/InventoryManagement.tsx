type StockBadgeInfo = {
  variant: "default" | "destructive" | "secondary" | "outline";
  className?: string;
  tooltip: string;
  showIcon: boolean;
};

const getStockBadgeInfo = (
  qty: number,
  type: "ats" | "atp",
  reorderPoint: number
): StockBadgeInfo => {
  if (qty < 0) {
    return {
      variant: "destructive",
      tooltip: `Stock deficit: ${Math.abs(qty)} units short`,
      showIcon: true,
    };
  }
  if (type === "ats" && qty === 0) {
    return {
      variant: "default",
      className: "bg-amber-500 text-white hover:bg-amber-500/80 border-transparent",
      tooltip: "No units available to ship",
      showIcon: true,
    };
  }
  if (type === "atp" && qty <= reorderPoint) {
    return {
      variant: "default",
      className: "bg-amber-500 text-white hover:bg-amber-500/80 border-transparent",
      tooltip: `At or below reorder point (${reorderPoint}). Consider reordering.`,
      showIcon: true,
    };
  }
  return {
    variant: "default",
    tooltip: "Stock level healthy",
    showIcon: false,
  };
};
