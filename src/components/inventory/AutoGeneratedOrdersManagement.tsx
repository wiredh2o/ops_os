import React, { useState, useEffect, useRef } from 'react';
import { supabase } from '@/integrations/supabase/client';
import { useToast } from '@/hooks/use-toast';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Badge } from '@/components/ui/badge';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import { Tooltip, TooltipContent, TooltipProvider, TooltipTrigger } from '@/components/ui/tooltip';
import { AlertTriangle, CheckCircle, XCircle, Clock, Package, Factory, Send, Trash2, Archive, RefreshCw, Info } from 'lucide-react';
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
  AlertDialogTrigger,
} from "@/components/ui/alert-dialog";
import { SendToVendorDialog } from '@/components/purchasing/SendToVendorDialog';

interface AutoGeneratedPurchaseOrder {
  id: string;
  purchase_order_number: string;
  supplier_id: string;
  supplier_name: string;
  status: string;
  source_reason: string;
  expected_delivery_date: string;
  order_date: string;
  created_at: string;
  total_amount: number;
  items_count: number;
  has_receipts: boolean;
  // Item-level details for order summary
  item_sku: string | null;
  quantity_ordered: number;
  unit_price: number;
  line_total: number;
  // Shipping fields
  ship_by_date: string | null;
  requested_shipping_carrier: string | null;
  requested_shipping_method: string | null;
}

interface AutoGeneratedProductionOrder {
  id: string;
  order_number: string;
  status: string;
  source_reason: string;
  due_date: string;
  created_at: string;
  items_count: number;
  has_completions: boolean;
  // Item-level details for order summary
  assembly_sku: string | null;
  quantity_ordered: number;
}

interface ReorderTrigger {
  id: string;
  item_type: string;
  current_quantity: number;
  reorder_point: number;
  days_until_stockout: number;
  trigger_reason: string;
  order_generated: boolean;
  created_at: string;
  item_sku?: string;
}

interface AutoGeneratedOrdersManagementProps {
  triggerOnMount?: boolean;
}

export const AutoGeneratedOrdersManagement: React.FC<AutoGeneratedOrdersManagementProps> = ({ 
  triggerOnMount = false 
}) => {
  const [purchaseOrders, setPurchaseOrders] = useState<AutoGeneratedPurchaseOrder[]>([]);
  const [productionOrders, setProductionOrders] = useState<AutoGeneratedProductionOrder[]>([]);
  const [reorderTriggers, setReorderTriggers] = useState<ReorderTrigger[]>([]);
  const [loading, setLoading] = useState(true);
  const [isCalculating, setIsCalculating] = useState(false);
  const [sendingPO, setSendingPO] = useState<AutoGeneratedPurchaseOrder | null>(null);
  const hasTriggeredRef = useRef(false);
  const { toast } = useToast();
  

  useEffect(() => {
    if (triggerOnMount && !hasTriggeredRef.current) {
      hasTriggeredRef.current = true;
      runCalculationAndRefresh();
    } else {
      fetchData();
    }
  }, [triggerOnMount]);

  const fetchData = async () => {
    try {
      setLoading(true);
      
      // Fetch auto-generated purchase orders with item details
      const { data: poData, error: poError } = await supabase
        .from('purchase_orders')
        .select(`
          id,
          purchase_order_number,
          supplier_id,
          status,
          source_reason,
          expected_delivery_date,
          order_date,
          created_at,
          total_amount,
          ship_by_date,
          requested_shipping_carrier,
          requested_shipping_method,
          suppliers!inner(name),
          purchase_order_items(
            id, 
            quantity, 
            unit_cost, 
            total_cost, 
            quantity_received,
            inventory_items(sku)
          )
        `)
        .eq('auto_generated', true)
        .order('created_at', { ascending: false });

      if (poError) throw poError;

      // Fetch auto-generated production orders with item details
      const { data: prodData, error: prodError } = await supabase
        .from('production_orders')
        .select(`
          id,
          order_number,
          status,
          source_reason,
          due_date,
          created_at,
          production_order_items(
            id, 
            quantity, 
            yield_quantity,
            assemblies(sku)
          )
        `)
        .eq('auto_generated', true)
        .order('created_at', { ascending: false });

      if (prodError) throw prodError;

      // Fetch recent reorder triggers
      const { data: triggerData, error: triggerError } = await supabase
        .from('reorder_triggers')
        .select('*')
        .order('created_at', { ascending: false })
        .limit(50);

      if (triggerError) throw triggerError;

      // Transform purchase orders with item-level details
      setPurchaseOrders(poData?.map(po => {
        const firstItem = po.purchase_order_items?.[0] as any;
        return {
          id: po.id,
          purchase_order_number: po.purchase_order_number,
          supplier_id: po.supplier_id,
          supplier_name: po.suppliers?.name || 'Unknown',
          status: po.status,
          source_reason: po.source_reason || '',
          expected_delivery_date: po.expected_delivery_date,
          order_date: po.order_date,
          created_at: po.created_at,
          total_amount: po.total_amount,
          items_count: po.purchase_order_items?.length || 0,
          has_receipts: po.purchase_order_items?.some((item: any) => item.quantity_received > 0) || false,
          // Shipping fields
          ship_by_date: po.ship_by_date || null,
          requested_shipping_carrier: po.requested_shipping_carrier || null,
          requested_shipping_method: po.requested_shipping_method || null,
          // Item-level details (use first item for auto-generated single-item orders)
          item_sku: firstItem?.inventory_items?.sku || null,
          quantity_ordered: firstItem?.quantity || 0,
          unit_price: firstItem?.unit_cost || 0,
          line_total: firstItem?.total_cost || 0,
        };
      }) || []);

      // Transform production orders with item-level details
      setProductionOrders(prodData?.map(prod => {
        const firstItem = prod.production_order_items?.[0] as any;
        return {
          id: prod.id,
          order_number: prod.order_number,
          status: prod.status,
          source_reason: prod.source_reason || '',
          due_date: prod.due_date,
          created_at: prod.created_at,
          items_count: prod.production_order_items?.length || 0,
          has_completions: prod.production_order_items?.some((item: any) => (item.yield_quantity || 0) > 0) || false,
          // Item-level details (use first item for auto-generated single-item orders)
          assembly_sku: firstItem?.assemblies?.sku || null,
          quantity_ordered: firstItem?.quantity || 0,
        };
      }) || []);

      // Fetch item SKUs for triggers
      const triggersWithSKU = await Promise.all(
        (triggerData || []).map(async (trigger) => {
          let item_sku = 'Unknown';
          
          if (trigger.item_type === 'inventory_item') {
            const { data: item } = await supabase
              .from('inventory_items')
              .select('sku')
              .eq('id', trigger.item_id)
              .single();
            if (item) item_sku = item.sku;
          } else if (trigger.item_type === 'assembly') {
            const { data: assembly } = await supabase
              .from('assemblies')
              .select('sku')
              .eq('id', trigger.item_id)
              .single();
            if (assembly) item_sku = assembly.sku;
          }
          
          return { ...trigger, item_sku };
        })
      );

      setReorderTriggers(triggersWithSKU);
    } catch (error) {
      console.error('Error fetching data:', error);
      toast({
        title: "Error loading orders",
        description: "Failed to fetch auto-generated orders",
        variant: "destructive",
      });
    } finally {
      setLoading(false);
    }
  };

  // Send to vendor - changes status from draft to sent (triggers QOO update)
  const sendToVendor = async (orderId: string) => {
    try {
      const { error } = await supabase
        .from('purchase_orders')
        .update({ status: 'sent' })
        .eq('id', orderId);

      if (error) throw error;

      fetchData();
    } catch (error: any) {
      console.error('Error sending to vendor:', error);
      toast({
        title: "Error",
        description: "Failed to send order to vendor",
        variant: "destructive",
      });
    }
  };

  // Delete draft PO - actually removes the record (no QOO impact since drafts don't affect it)
  const deleteDraftOrder = async (orderId: string, orderType: 'purchase' | 'production') => {
    try {
      const table = orderType === 'purchase' ? 'purchase_orders' : 'production_orders';
      const { error } = await supabase
        .from(table)
        .delete()
        .eq('id', orderId);

      if (error) throw error;

      fetchData();
    } catch (error: any) {
      console.error('Error deleting order:', error);
      toast({
        title: "Error",
        description: "Failed to delete draft order",
        variant: "destructive",
      });
    }
  };

  // Cancel sent order with no receipts - subtracts QOO
  const cancelSentOrder = async (orderId: string, orderType: 'purchase' | 'production') => {
    try {
      const table = orderType === 'purchase' ? 'purchase_orders' : 'production_orders';
      const { error } = await supabase
        .from(table)
        .update({ status: 'cancelled' })
        .eq('id', orderId);

      if (error) throw error;

      fetchData();
    } catch (error: any) {
      console.error('Error cancelling order:', error);
      toast({
        title: "Error",
        description: "Failed to cancel order",
        variant: "destructive",
      });
    }
  };

  // Close partially received order - subtracts remaining QOO
  const closePartialOrder = async (orderId: string, orderType: 'purchase' | 'production') => {
    try {
      const table = orderType === 'purchase' ? 'purchase_orders' : 'production_orders';
      const { error } = await supabase
        .from(table)
        .update({ status: 'closed' })
        .eq('id', orderId);

      if (error) throw error;

      fetchData();
    } catch (error: any) {
      console.error('Error closing order:', error);
      toast({
        title: "Error",
        description: "Failed to close order",
        variant: "destructive",
      });
    }
  };

  // Approve production order (start production)
  const approveProductionOrder = async (orderId: string) => {
    try {
      const { error } = await supabase
        .from('production_orders')
        .update({ status: 'approved' })
        .eq('id', orderId);

      if (error) throw error;

      fetchData();
    } catch (error: any) {
      console.error('Error approving production order:', error);
      toast({
        title: "Error",
        description: "Failed to approve production order",
        variant: "destructive",
      });
    }
  };

  const getStatusIcon = (status: string) => {
    switch (status) {
      case 'sent':
        return <Send className="h-4 w-4 text-blue-500" />;
      case 'partial':
        return <Package className="h-4 w-4 text-orange-500" />;
      case 'delivered':
      case 'approved':
        return <CheckCircle className="h-4 w-4 text-green-500" />;
      case 'cancelled':
      case 'closed':
        return <XCircle className="h-4 w-4 text-red-500" />;
      case 'draft':
      case 'pending':
        return <Clock className="h-4 w-4 text-yellow-500" />;
      default:
        return <Clock className="h-4 w-4 text-muted-foreground" />;
    }
  };

  const getUrgencyColor = (daysUntilStockout?: number) => {
    if (!daysUntilStockout) return 'text-muted-foreground';
    if (daysUntilStockout <= 0) return 'text-destructive font-semibold';
    if (daysUntilStockout <= 3) return 'text-orange-600 font-semibold';
    if (daysUntilStockout <= 7) return 'text-yellow-600';
    return 'text-muted-foreground';
  };

  // Tooltip component for formula variables
  const FormulaVar = ({ label, tooltip, value }: { label: string; tooltip: string; value?: string | number }) => (
    <Tooltip>
      <TooltipTrigger asChild>
        <span className="inline-flex items-center gap-1 cursor-help underline decoration-dotted decoration-muted-foreground/50">
          {label}
          <Info className="h-3 w-3 text-muted-foreground" />
        </span>
      </TooltipTrigger>
      <TooltipContent className="max-w-xs">
        <p>{tooltip}</p>
      </TooltipContent>
    </Tooltip>
  );

  // Helper function to format complete formula display with plain English
  const formatFriendlyReason = (reason: string) => {
    // Parse FRIENDLY format: FRIENDLY|demandRate|leadTime|waitQty|safetyStock|reorderPoint|effectiveInv|orderQty|sku|moq|naturalQty|demandStdDev|shortage|onHand|allocated|onOrder|demandDuringLeadTime
    if (reason?.startsWith('FRIENDLY|')) {
      const parts = reason.split('|');
      const demandRate = parseFloat(parts[1] || '0');
      const leadTime = parseInt(parts[2] || '0');
      const waitQty = parseInt(parts[3] || '0');
      const safetyStock = parseInt(parts[4] || '0');
      const reorderPoint = parseInt(parts[5] || '0');
      const effectiveInv = parseInt(parts[6] || '0');
      const orderQty = parseInt(parts[7] || '0');
      const moq = parseInt(parts[9] || '1');
      const naturalQty = parseInt(parts[10] || '0');
      const demandStdDev = parseFloat(parts[11] || '0');
      const shortage = parseInt(parts[12] || '0');
      // New variables for Current Status
      const onHand = parseInt(parts[13] || '0');
      const allocated = parseInt(parts[14] || '0');
      const onOrder = parseInt(parts[15] || '0');
      
      const moqApplied = orderQty > naturalQty;
      
      // Calculate typical usage during lead time (for safety level explanation)
      const typicalUsageDuringWait = Math.ceil(demandRate * leadTime);

      const moqNote = moqApplied ? ' (vendor minimum)' : '';
      
      return (
        <p className="mt-3 text-sm text-muted-foreground">
          Ordering <strong>{orderQty} units</strong>{moqNote} because we have{' '}
          <strong>{effectiveInv} available</strong> but need <strong>{reorderPoint}</strong> to cover the{' '}
          <strong>{leadTime}-day</strong> lead time
          {!moqApplied && ` (${shortage} shortage + ${waitQty} for the wait)`}.
        </p>
      );
    }
    
    // Parse old "Enhanced LEAN Pull Order:" format for backward compatibility
    if (reason?.includes('Demand Rate=')) {
      const demandMatch = reason.match(/Demand Rate=([\d.]+)/);
      const safetyMatch = reason.match(/Safety Stock=(\d+)/);
      const moqMatch = reason.match(/MOQ Coverage=([\d.]+)/);
      
      if (demandMatch && safetyMatch && moqMatch) {
        const demandRate = parseFloat(demandMatch[1]);
        const safetyStock = parseInt(safetyMatch[1]);
        const leadTime = Math.round(parseFloat(moqMatch[1]));
        const waitQty = Math.round(demandRate * leadTime);
        const reorderPoint = waitQty + safetyStock;
        
        return (
          <div className="mt-4 bg-amber-50 border border-amber-200 rounded-lg p-4">
            <h4 className="font-semibold text-amber-900 mb-3">Legacy Order Calculation</h4>
            <div className="space-y-1 text-sm">
              <p>Daily Demand: <strong>{demandRate.toFixed(2)}</strong></p>
              <p>Lead Time: <strong>{leadTime} days</strong></p>
              <p>Safety Buffer: <strong>{safetyStock}</strong></p>
              <p>Reorder Point: <strong>{reorderPoint}</strong></p>
            </div>
          </div>
        );
      }
    }
    
    // Fallback for unknown formats
    return <p className="text-sm text-muted-foreground mt-2">Reason: {reason}</p>;
  };

  // Helper function to render order summary at the bottom of cards
  const renderOrderSummary = (quantity: number, unitPrice: number, lineTotal: number, itemSku: string | null) => {
    // Don't render if no quantity or missing price data
    if (!quantity || quantity <= 0) return null;
    
    // Safely handle undefined/null values
    const safeUnitPrice = unitPrice ?? 0;
    const safeLineTotal = lineTotal ?? 0;
    
    return (
      <div className="bg-slate-100 border border-slate-300 rounded-lg p-3 mt-3">
        <p className="font-medium text-slate-900 mb-1">📦 Order Summary</p>
        <p className="text-slate-700">
          Ordering: <strong>{quantity}</strong> units @ <strong>${safeUnitPrice.toFixed(2)}</strong> each = <strong>${safeLineTotal.toFixed(2)}</strong>
        </p>
        {itemSku && (
          <p className="text-sm text-slate-600 mt-1">Item: {itemSku}</p>
        )}
      </div>
    );
  };

  // Helper function to render production order summary (no price, just quantity)
  const renderProductionOrderSummary = (quantity: number, assemblySku: string | null) => {
    if (quantity <= 0) return null;
    
    return (
      <div className="bg-purple-50 border border-purple-200 rounded-lg p-3 mt-3">
        <p className="font-medium text-purple-900 mb-1">🏭 Production Summary</p>
        <p className="text-purple-800">
          Producing: <strong>{quantity}</strong> units
        </p>
        {assemblySku && (
          <p className="text-sm text-purple-700 mt-1">Assembly: {assemblySku}</p>
        )}
      </div>
    );
  };

  const runCalculationAndRefresh = async () => {
    setIsCalculating(true);
    setLoading(true);
    
    try {
      const { data, error } = await supabase.functions.invoke('manual-calculation-trigger', {
        body: { triggerTTM: true, triggerReorder: true }
      });

      if (error) throw error;

      if (data?.success) {
        // Refresh auto orders list
        await fetchData();
      } else {
        throw new Error(data?.error || 'Calculation failed');
      }
    } catch (error: any) {
      console.error('Error during calculation:', error);
      toast({
        title: "Calculation Error",
        description: error.message || "Failed to run calculations",
        variant: "destructive",
      });
      setLoading(false);
    } finally {
      setIsCalculating(false);
    }
  };

  if (loading && !isCalculating) {
    return (
      <div className="text-center py-8">
        <div className="inline-block animate-spin rounded-full h-8 w-8 border-b-2 border-primary"></div>
        <p className="mt-2 text-sm text-muted-foreground">Loading auto-generated orders...</p>
      </div>
    );
  }

  return (
    <div className="space-y-6">
      <div className="flex items-center justify-between">
        <div>
          <h2 className="text-2xl font-bold text-foreground">Auto-Generated Orders</h2>
          <p className="text-muted-foreground">Proactive orders generated to prevent stockouts</p>
        </div>
        <Button 
          onClick={runCalculationAndRefresh} 
          variant="outline"
          disabled={isCalculating}
          className="gap-2"
        >
          <RefreshCw className={`h-4 w-4 ${isCalculating ? "animate-spin" : ""}`} />
          {isCalculating ? "Calculating..." : "Refresh & Calculate"}
        </Button>
      </div>

      {isCalculating && (
        <div className="text-center py-8">
          <div className="inline-block animate-spin rounded-full h-8 w-8 border-b-2 border-primary"></div>
          <p className="mt-2 text-sm text-muted-foreground">Calculating reorder points and generating orders...</p>
        </div>
      )}

      <Tabs defaultValue="purchase" className="space-y-6">
        <TabsList className="grid w-full grid-cols-3">
          <TabsTrigger value="purchase">
            Purchase Orders ({purchaseOrders.length})
          </TabsTrigger>
          <TabsTrigger value="production">
            Production Orders ({productionOrders.length})
          </TabsTrigger>
          <TabsTrigger value="triggers">
            Reorder Triggers ({reorderTriggers.length})
          </TabsTrigger>
        </TabsList>

        <TabsContent value="purchase" className="space-y-4">
          {purchaseOrders.length === 0 ? (
            <Card>
              <CardContent className="flex flex-col items-center justify-center py-12">
                <Package className="h-12 w-12 text-muted-foreground mb-4" />
                <h3 className="text-lg font-semibold mb-2">No auto-generated purchase orders</h3>
                <p className="text-muted-foreground text-center">
                  The system will automatically generate purchase orders when inventory reaches reorder points
                </p>
              </CardContent>
            </Card>
          ) : (
            <div className="grid gap-4">
              {purchaseOrders.map((order) => (
                <Card key={order.id}>
                  <CardContent className="p-6">
                    <div className="flex items-center justify-between mb-4">
                      <div className="flex items-center gap-3">
                        <div className="flex items-center gap-2">
                          {getStatusIcon(order.status)}
                          <h3 className="font-semibold text-lg">{order.purchase_order_number}</h3>
                        </div>
                        <Badge variant="secondary">Auto-Generated</Badge>
                        <Badge variant={
                          order.status === 'draft' ? 'outline' : 
                          order.status === 'sent' ? 'default' : 
                          order.status === 'partial' ? 'secondary' :
                          order.status === 'delivered' ? 'default' : 
                          'destructive'
                        }>
                          {order.status}
                        </Badge>
                      </div>
                      <div className="flex gap-2">
                        {/* Draft: Send to Vendor or Delete */}
                        {order.status === 'draft' && (
                          <>
                            <Button 
                              size="sm" 
                              variant="default"
                              onClick={() => setSendingPO(order)}
                            >
                              <Send className="mr-1 h-3 w-3" />
                              Send to Vendor
                            </Button>
                            <AlertDialog>
                              <AlertDialogTrigger asChild>
                                <Button size="sm" variant="outline">
                                  <Trash2 className="mr-1 h-3 w-3" />
                                  Delete
                                </Button>
                              </AlertDialogTrigger>
                              <AlertDialogContent>
                                <AlertDialogHeader>
                                  <AlertDialogTitle>Delete Draft PO?</AlertDialogTitle>
                                  <AlertDialogDescription>
                                    This will remove {order.purchase_order_number}. If this item still needs reordering, a new PO will be generated on the next calculation run.
                                  </AlertDialogDescription>
                                </AlertDialogHeader>
                                <AlertDialogFooter>
                                  <AlertDialogCancel>Keep</AlertDialogCancel>
                                  <AlertDialogAction onClick={() => deleteDraftOrder(order.id, 'purchase')}>
                                    Delete
                                  </AlertDialogAction>
                                </AlertDialogFooter>
                              </AlertDialogContent>
                            </AlertDialog>
                          </>
                        )}
                        {/* Sent with no receipts: Cancel Order */}
                        {order.status === 'sent' && !order.has_receipts && (
                          <Button 
                            size="sm" 
                            variant="outline"
                            onClick={() => cancelSentOrder(order.id, 'purchase')}
                          >
                            <XCircle className="mr-1 h-3 w-3" />
                            Cancel Order
                          </Button>
                        )}
                        {/* Sent with receipts or Partial: Close Order */}
                        {((order.status === 'sent' && order.has_receipts) || order.status === 'partial') && (
                          <Button 
                            size="sm" 
                            variant="outline"
                            onClick={() => closePartialOrder(order.id, 'purchase')}
                          >
                            <Archive className="mr-1 h-3 w-3" />
                            Close Order
                          </Button>
                        )}
                      </div>
                    </div>
                    <div className="space-y-2">
                      <p className="text-muted-foreground">Supplier: {order.supplier_name}</p>
                      <p className="text-muted-foreground">Expected: {order.expected_delivery_date ? new Date(order.expected_delivery_date).toLocaleDateString() : 'Not set'}</p>
                      <p className="text-sm text-muted-foreground">Created: {new Date(order.created_at).toLocaleString()}</p>
                      
                      {/* Kid-friendly formula explanation */}
                      {formatFriendlyReason(order.source_reason)}
                      
                      {/* Order Summary at BOTTOM */}
                      {renderOrderSummary(order.quantity_ordered, order.unit_price, order.line_total, order.item_sku)}
                    </div>
                  </CardContent>
                </Card>
              ))}
            </div>
          )}
        </TabsContent>

        <TabsContent value="production" className="space-y-4">
          {productionOrders.length === 0 ? (
            <Card>
              <CardContent className="flex flex-col items-center justify-center py-12">
                <Factory className="h-12 w-12 text-muted-foreground mb-4" />
                <h3 className="text-lg font-semibold mb-2">No auto-generated production orders</h3>
                <p className="text-muted-foreground text-center">
                  The system will automatically generate production orders when assemblies reach reorder points
                </p>
              </CardContent>
            </Card>
          ) : (
            <div className="grid gap-4">
              {productionOrders.map((order) => (
                <Card key={order.id}>
                  <CardContent className="p-6">
                    <div className="flex items-center justify-between mb-4">
                      <div className="flex items-center gap-3">
                        <div className="flex items-center gap-2">
                          {getStatusIcon(order.status)}
                          <h3 className="font-semibold text-lg">{order.order_number}</h3>
                        </div>
                        <Badge variant="secondary">Auto-Generated</Badge>
                        <Badge variant={
                          order.status === 'pending' ? 'outline' : 
                          order.status === 'approved' || order.status === 'in_progress' ? 'default' : 
                          order.status === 'completed' ? 'default' :
                          'destructive'
                        }>
                          {order.status}
                        </Badge>
                      </div>
                      <div className="flex gap-2">
                        {/* Pending: Approve or Delete */}
                        {order.status === 'pending' && (
                          <>
                            <Button 
                              size="sm" 
                              variant="default"
                              onClick={() => approveProductionOrder(order.id)}
                            >
                              <CheckCircle className="mr-1 h-3 w-3" />
                              Approve
                            </Button>
                            <AlertDialog>
                              <AlertDialogTrigger asChild>
                                <Button size="sm" variant="outline">
                                  <Trash2 className="mr-1 h-3 w-3" />
                                  Delete
                                </Button>
                              </AlertDialogTrigger>
                              <AlertDialogContent>
                                <AlertDialogHeader>
                                  <AlertDialogTitle>Delete Draft Production Order?</AlertDialogTitle>
                                  <AlertDialogDescription>
                                    This will remove {order.order_number}. If this assembly still needs production, a new order will be generated on the next calculation run.
                                  </AlertDialogDescription>
                                </AlertDialogHeader>
                                <AlertDialogFooter>
                                  <AlertDialogCancel>Keep</AlertDialogCancel>
                                  <AlertDialogAction onClick={() => deleteDraftOrder(order.id, 'production')}>
                                    Delete
                                  </AlertDialogAction>
                                </AlertDialogFooter>
                              </AlertDialogContent>
                            </AlertDialog>
                          </>
                        )}
                        {/* In progress with no completions: Cancel */}
                        {(order.status === 'approved' || order.status === 'in_progress') && !order.has_completions && (
                          <Button 
                            size="sm" 
                            variant="outline"
                            onClick={() => cancelSentOrder(order.id, 'production')}
                          >
                            <XCircle className="mr-1 h-3 w-3" />
                            Cancel
                          </Button>
                        )}
                        {/* In progress with completions: Close */}
                        {(order.status === 'approved' || order.status === 'in_progress') && order.has_completions && (
                          <Button 
                            size="sm" 
                            variant="outline"
                            onClick={() => closePartialOrder(order.id, 'production')}
                          >
                            <Archive className="mr-1 h-3 w-3" />
                            Close
                          </Button>
                        )}
                      </div>
                    </div>
                    <div className="space-y-2">
                      <p className="text-muted-foreground">Due: {order.due_date ? new Date(order.due_date).toLocaleDateString() : 'Not set'}</p>
                      <p className="text-sm text-muted-foreground">Created: {new Date(order.created_at).toLocaleString()}</p>
                      
                      {/* Kid-friendly formula explanation */}
                      {formatFriendlyReason(order.source_reason)}
                      
                      {/* Production Summary at BOTTOM */}
                      {renderProductionOrderSummary(order.quantity_ordered, order.assembly_sku)}
                    </div>
                  </CardContent>
                </Card>
              ))}
            </div>
          )}
        </TabsContent>

        <TabsContent value="triggers" className="space-y-4">
          {reorderTriggers.length === 0 ? (
            <Card>
              <CardContent className="flex flex-col items-center justify-center py-12">
                <AlertTriangle className="h-12 w-12 text-muted-foreground mb-4" />
                <h3 className="text-lg font-semibold mb-2">No reorder triggers</h3>
                <p className="text-muted-foreground text-center">
                  All inventory levels are healthy
                </p>
              </CardContent>
            </Card>
          ) : (
            <div className="grid gap-4">
              {reorderTriggers.map((trigger) => (
                <Card key={trigger.id}>
                  <CardContent className="p-6">
                    <div className="flex items-center justify-between mb-4">
                      <div className="flex items-center gap-3">
                        <h3 className="font-semibold text-lg">{trigger.item_sku}</h3>
                        <Badge variant={trigger.item_type === 'inventory_item' ? 'default' : 'secondary'}>
                          {trigger.item_type === 'inventory_item' ? 'Item' : 'Assembly'}
                        </Badge>
                        {trigger.order_generated && (
                          <Badge variant="default" className="bg-green-100 text-green-800">
                            Order Generated
                          </Badge>
                        )}
                      </div>
                      <div className="text-right">
                        <p className={`text-sm ${getUrgencyColor(trigger.days_until_stockout)}`}>
                          {trigger.days_until_stockout <= 0 
                            ? 'STOCKOUT RISK' 
                            : `${trigger.days_until_stockout} days until stockout`}
                        </p>
                      </div>
                    </div>
                    <div className="space-y-2">
                      <div className="flex justify-between">
                        <span className="text-muted-foreground">Current Stock:</span>
                        <span className="font-medium">{trigger.current_quantity}</span>
                      </div>
                      <div className="flex justify-between">
                        <span className="text-muted-foreground">Reorder Point:</span>
                        <span className="font-medium">{trigger.reorder_point}</span>
                      </div>
                      <p className="text-sm text-muted-foreground">{trigger.trigger_reason}</p>
                      <p className="text-xs text-muted-foreground">Detected: {new Date(trigger.created_at).toLocaleString()}</p>
                    </div>
                  </CardContent>
                </Card>
              ))}
            </div>
          )}
        </TabsContent>
      </Tabs>

      {/* Send to Vendor Dialog */}
      {sendingPO && (
        <SendToVendorDialog
          purchaseOrder={{
            id: sendingPO.id,
            purchase_order_number: sendingPO.purchase_order_number,
            order_date: sendingPO.order_date,
            supplier_id: sendingPO.supplier_id,
            notes: null,
            subtotal: sendingPO.total_amount,
            total: sendingPO.total_amount,
            ship_by_date: sendingPO.ship_by_date,
            requested_shipping_carrier: sendingPO.requested_shipping_carrier,
            requested_shipping_method: sendingPO.requested_shipping_method,
          }}
          onClose={() => setSendingPO(null)}
          onSuccess={() => {
            setSendingPO(null);
            fetchData();
          }}
        />
      )}
    </div>
  );
};